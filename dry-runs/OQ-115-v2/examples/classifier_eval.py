"""Evaluates the real KeywordClassifier against held-out sets of realistic,
informally-phrased legal task descriptions. Unlike scenarios.json (written
by the same process as the classifier's keyword lists), each
classifier_holdout_*.json file here was generated by a fresh subagent that
never read router/taxonomy.py -- see README's "Independent classifier
evaluation" section for how and why.

Run: python examples/classifier_eval.py [path-to-holdout.json ...]
Defaults to every classifier_holdout_*.json file in this directory.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from router.classifier import KeywordClassifier  # noqa: E402


def evaluate(holdout_path: Path) -> None:
    cases = json.loads(holdout_path.read_text(encoding="utf-8"))
    clf = KeywordClassifier()

    correct = 0
    mismatches = []
    for case in cases:
        result = clf.classify(case["text"])
        expected = case["expected_task_type"]
        if result.task_type.value == expected:
            correct += 1
        else:
            mismatches.append((case["text"], expected, result.task_type.value, result.matched_keywords))

    print(f"=== {holdout_path.name}: {correct}/{len(cases)} correct ({100 * correct / len(cases):.0f}%) ===")
    for text, expected, predicted, matched in mismatches:
        print(f"  MISS: expected={expected!r} predicted={predicted!r} matched={list(matched)}")
        print(f"        {text!r}")
    print()


def main():
    args = sys.argv[1:]
    if args:
        paths = [Path(a) for a in args]
    else:
        paths = sorted(Path(__file__).parent.glob("classifier_holdout_*.json"))
    if not paths:
        print("No holdout files found (expected examples/classifier_holdout_*.json)")
        return
    for path in paths:
        evaluate(path)


if __name__ == "__main__":
    main()
